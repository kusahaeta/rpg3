  // 住居。face = 玄関の向き（n/s/e/w）。style: module（ステーション）/ snow（雪国）/ xian（仙舟）
  house(x, z, w, d, h, face, style, mat) {
    const side = face === 'e' || face === 'w';
    const f = { n: [0, -1], s: [0, 1], e: [1, 0], w: [-1, 0] }[face];
    const W = side ? d : w, D = side ? w : d;     // 玄関のある面の幅 W、奥行き D
    const body = style === 'xian' ? 'plaster' : style === 'module' ? 'metal2' : null;
    this.box(x, z, w, h, d, mat || body || (this.r() < 0.5 ? 'house' : 'plaster'));
    const at = (u, y, o = 0.02) => [x + f[0] * (D / 2 + o) + (side ? 0 : u), y, z + f[1] * (D / 2 + o) + (side ? u : 0)];
    const faceRy = Math.atan2(f[0], f[1]);
    // 玄関と窓
    const door = style === 'module' ? this.glow('#ffcf8a', 1.4) : 'wood2';
    this.mesh(new THREE.PlaneGeometry(1.3, 2.2), this.M(door), ...at(0, 1.1), { ry: faceRy, noShadow: true });
    const winC = style === 'module' ? '#8ae0ff' : '#ffd27a';
    for (const u of [-W / 2 + 1.3, W / 2 - 1.3]) if (W > 4.5) this.mesh(new THREE.PlaneGeometry(1, 1), this.glow(winC, 1.5), ...at(u, Math.min(2.4, h - 1)), { ry: faceRy, noShadow: true });
    if (h > 5) for (const u of [-W / 4, W / 4]) this.mesh(new THREE.PlaneGeometry(0.9, 0.9), this.glow(winC, 1.3), ...at(u, h - 1.6), { ry: faceRy, noShadow: true });
    if (style === 'module') {
      this.mesh(new THREE.BoxGeometry(w + 0.3, 0.3, d + 0.3), 'metal', x, h + 0.15, z);
      this.mesh(new THREE.BoxGeometry(w + 0.34, 0.08, d + 0.34), this.glow('#ffcf8a', 1.8), x, h - 0.1, z, { noShadow: true });
      this.mesh(new THREE.BoxGeometry(1.6, 0.12, 0.5), 'metal', ...at(0, 2.5, 0.25), { ry: faceRy });
    } else if (style === 'snow') {
      this.roof(x, h + 1.2, z, w / 2 + 0.5, d / 2 + 0.5, 2.4);
      this.mesh(new THREE.BoxGeometry(w + 0.4, 0.25, d + 0.4), 'snow', x, h + 0.05, z);
      this.mesh(new THREE.BoxGeometry(0.8, 1.6, 0.8), 'stone2', x + w * 0.25, h + 1.4, z - d * 0.2);
    } else if (style === 'xian') {
      for (const u of [-W / 2 + 0.4, W / 2 - 0.4]) this.mesh(new THREE.CylinderGeometry(0.18, 0.18, h, 8), 'red', ...at(u, h / 2, 0.3));
      this.mesh(new THREE.BoxGeometry(w + 0.2, 0.3, d + 0.2), 'red', x, h + 0.15, z);
      this.roof(x, h + 1.4, z, w / 2 + 1.1, d / 2 + 1.1, 2.2);
      this.mesh(new THREE.SphereGeometry(0.2, 8, 6), this.glow('#ffcf6a', 2), x, h + 2.5, z);
      const [lx, , lz] = at(W / 2 - 1, 0, 0.5);
      this.mesh(new THREE.CylinderGeometry(0.25, 0.25, 0.45, 10), this.glow('#ff8a3a', 1.6), lx, 2.7, lz, { noShadow: true });
    }
    this.v.reserved.push({ x, z, r: Math.max(w, d) / 2 });
  }
